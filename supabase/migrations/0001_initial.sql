begin;

create extension if not exists pgcrypto with schema extensions;
create extension if not exists pgroonga with schema extensions;
create extension if not exists pg_trgm with schema extensions;

create type public.profile_role as enum ('user', 'admin');
create type public.interaction_status as enum ('WATCHED', 'WATCHLIST', 'NONE');
create type public.offer_type as enum ('flatrate', 'rent', 'buy');
create type public.video_platform as enum ('youtube', 'tiktok');
create type public.video_status as enum ('pending', 'approved', 'rejected');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text check (char_length(display_name) <= 80),
  avatar_url text,
  role public.profile_role not null default 'user',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.movies (
  id uuid primary key default extensions.gen_random_uuid(),
  tmdb_id bigint not null unique check (tmdb_id > 0),
  title text not null check (char_length(title) between 1 and 500),
  original_title text,
  overview text not null default '',
  poster_path text,
  backdrop_path text,
  release_date date,
  runtime integer check (runtime is null or runtime between 0 and 1440),
  vote_average numeric(4,2) not null default 0 check (vote_average between 0 and 10),
  popularity numeric not null default 0 check (popularity >= 0),
  genres text[] not null default '{}',
  emotional_tags text[] not null default '{}',
  search_text text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.providers (
  id bigint generated by default as identity primary key,
  tmdb_provider_id integer not null unique check (tmdb_provider_id > 0),
  name text not null,
  slug text not null unique,
  logo_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.movie_providers (
  movie_id uuid not null references public.movies(id) on delete cascade,
  provider_id bigint not null references public.providers(id) on delete cascade,
  country text not null default 'JP' check (country ~ '^[A-Z]{2}$'),
  offer_type public.offer_type not null,
  tmdb_link text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (movie_id, provider_id, country, offer_type)
);

create table public.movie_videos (
  id uuid primary key default extensions.gen_random_uuid(),
  movie_id uuid not null references public.movies(id) on delete cascade,
  platform public.video_platform not null,
  video_id text not null,
  url text,
  status public.video_status not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (platform, video_id)
);

create table public.user_movie_interactions (
  user_id uuid not null references auth.users(id) on delete cascade,
  movie_id uuid not null references public.movies(id) on delete cascade,
  status public.interaction_status not null default 'NONE',
  is_favorite boolean not null default false,
  rating smallint check (rating is null or rating between 1 and 5),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, movie_id)
);

create table public.reviews (
  id uuid primary key default extensions.gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  movie_id uuid not null references public.movies(id) on delete cascade,
  body text not null check (char_length(btrim(body)) between 1 and 4000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, movie_id)
);

create table public.search_events (
  id bigint generated always as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  query text not null default '' check (char_length(query) <= 500),
  filters jsonb not null default '{}'::jsonb,
  result_count integer check (result_count is null or result_count >= 0),
  created_at timestamptz not null default now()
);

create table public.sync_runs (
  id uuid primary key default extensions.gen_random_uuid(),
  source text not null,
  status text not null check (status in ('running', 'succeeded', 'failed')),
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  records_processed integer not null default 0 check (records_processed >= 0),
  error_message text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.set_movie_search_text()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.search_text := btrim(concat_ws(
    ' ',
    new.title,
    new.original_title,
    new.overview,
    array_to_string(new.genres, ' '),
    array_to_string(new.emotional_tags, ' ')
  ));
  return new;
end;
$$;

create trigger movies_search_text_before_write
before insert or update of title, original_title, overview, genres, emotional_tags
on public.movies for each row execute function public.set_movie_search_text();

create trigger profiles_updated_at before update on public.profiles
for each row execute function public.set_updated_at();
create trigger movies_updated_at before update on public.movies
for each row execute function public.set_updated_at();
create trigger providers_updated_at before update on public.providers
for each row execute function public.set_updated_at();
create trigger movie_providers_updated_at before update on public.movie_providers
for each row execute function public.set_updated_at();
create trigger movie_videos_updated_at before update on public.movie_videos
for each row execute function public.set_updated_at();
create trigger interactions_updated_at before update on public.user_movie_interactions
for each row execute function public.set_updated_at();
create trigger reviews_updated_at before update on public.reviews
for each row execute function public.set_updated_at();
create trigger sync_runs_updated_at before update on public.sync_runs
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name, avatar_url)
  values (
    new.id,
    left(coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name', ''), 80),
    new.raw_user_meta_data ->> 'avatar_url'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

create or replace function public.protect_profile_role()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if new.role is distinct from old.role
    and coalesce(auth.role(), '') <> 'service_role'
    and not public.is_admin()
  then
    raise exception 'Only administrators may change profile roles';
  end if;
  return new;
end;
$$;

create trigger profiles_protect_role_before_update
before update of role on public.profiles
for each row execute function public.protect_profile_role();

